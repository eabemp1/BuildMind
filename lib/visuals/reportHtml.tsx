/**
 * lib/visuals/reportHtml.tsx
 *
 * Turns a VisualSpec into one self-contained HTML file: no scripts needed to
 * read it, no external requests, light and dark themes, and print styles so
 * "Print → Save as PDF" gives a clean multi-page report. It draws with the
 * same VisualBoard the app uses, so the file and the screen cannot disagree.
 */

import React from "react";
import { renderStatic } from "./staticRender";
import { VisualBoard } from "@/components/visuals/VisualBoard";
import type { VisualSpec } from "./spec";

const esc = (s: string) => s.replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c] as string));

const DARK = "--bm-bg:#0e0f12;--bm-bg2:#15161b;--bm-bg3:#1b1d24;--bm-bg4:#262933;--bm-border:#2a2d37;--bm-text:#ecebe6;--bm-text2:#c4c2b8;--bm-text3:#8f8d82;--bm-green:#4ade80;--bm-amber:#f5a524;--bm-red:#f87171;--bm-accent:#d4af37;--bm-text-inv:#15130a;";
const LIGHT = "--bm-bg:#f6f4ec;--bm-bg2:#ffffff;--bm-bg3:#f0ede2;--bm-bg4:#e2ded0;--bm-border:#d9d4c3;--bm-text:#1a1912;--bm-text2:#454236;--bm-text3:#7a7665;--bm-green:#1f8f55;--bm-amber:#b7791f;--bm-red:#c2413a;--bm-accent:#9a7410;--bm-text-inv:#fffdf5;";

export function renderVisualReportHtml(spec: VisualSpec, opts: { footer?: string } = {}): string {
  const board = renderStatic(<VisualBoard spec={spec} />);
  const footer = opts.footer ?? "Generated by BuildMind from your own activity. Every figure is a field from your record.";
  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${esc(spec.title)} · BuildMind</title>
<style>
:root{${DARK}color-scheme:dark}
@media (prefers-color-scheme:light){:root{${LIGHT}color-scheme:light}}
*{box-sizing:border-box}
body{margin:0;background:var(--bm-bg);color:var(--bm-text);font-family:'Inter',system-ui,-apple-system,Segoe UI,sans-serif;-webkit-font-smoothing:antialiased}
.wrap{max-width:1100px;margin:0 auto;padding:32px 20px 56px}
.bar{display:flex;justify-content:space-between;align-items:center;gap:12px;margin-bottom:22px;font-size:12px;color:var(--bm-text3)}
.brand{font-family:'DM Mono',ui-monospace,monospace;letter-spacing:.14em;text-transform:uppercase}
.btn{font:inherit;font-size:12px;font-weight:600;color:var(--bm-text-inv);background:var(--bm-accent);border:0;border-radius:8px;padding:8px 14px;cursor:pointer}
footer{margin-top:28px;font-size:11.5px;color:var(--bm-text3);line-height:1.6}
@media print{
  :root{${LIGHT}color-scheme:light}
  body{background:#fff}
  .btn{display:none}
  .wrap{max-width:none;padding:0}
}
</style>
</head>
<body>
<div class="wrap">
<div class="bar"><span class="brand">BuildMind</span><button class="btn" onclick="window.print()">Print or save as PDF</button></div>
${board}
<footer>${esc(footer)}</footer>
</div>
</body>
</html>`;
}
